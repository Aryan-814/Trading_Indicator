#!/usr/bin/env python3
"""Generate markdown tables from models/v1/metrics.json and reports/experiments.csv.

Usage: python scripts/make_report_tables.py
Output: reports/generated_tables.md
"""
import json
import pandas as pd

METRICS = "models/v1/metrics.json"
EXPERIMENTS = "reports/experiments.csv"
OUT = "reports/generated_tables.md"


def fmt(v, pct=False, dp=2):
    if v is None or (isinstance(v, float) and v != v):
        return "—"
    if pct:
        return f"{v * 100:.{dp}f}%"
    return f"{v:.{dp}f}"


def main():
    with open(METRICS) as fh:
        m = json.load(fh)

    exp = pd.read_csv(EXPERIMENTS)
    lgb_exp = exp[exp["model"] == "lightgbm"].copy()
    if "run_id" in lgb_exp.columns and (lgb_exp["run_id"] != "lgb_aborted").any():
        latest_run = lgb_exp[lgb_exp["run_id"] != "lgb_aborted"]["run_id"].iloc[-1]
        lgb_final = lgb_exp[lgb_exp["run_id"] == latest_run].copy()
    else:
        latest_run = "—"
        lgb_final = lgb_exp

    val = m["validation"]
    ho = m["holdout"]
    n_trials = m.get("trials_total", len(exp))

    val_pol = val["policy"]
    ho_pol = ho["policy"]

    val_p = val_pol.get("perm_pvalue", float("nan"))
    val_p_adj = min(1.0, val_p * n_trials) if val_p == val_p else float("nan")
    ho_p = ho_pol.get("perm_pvalue", float("nan"))

    # Verified day counts: 248 validation days (2025), 203 holdout days (2026)
    val_sig_day = val_pol.get("n_signals", 0) / 248.0
    ho_sig_day = ho_pol.get("n_signals", 0) / 203.0

    lines = []
    lines.append("# Generated Performance Tables\n")
    lines.append(
        f"*Source: `{METRICS}` and `{EXPERIMENTS}` (run `{latest_run}`). "
        "Generated by `scripts/make_report_tables.py`. Do not edit by hand.*\n"
    )

    # --- Performance summary ---
    lines.append("## Performance Summary\n")
    lines.append(f"*Source: `{METRICS}`*\n")
    lines.append("| Metric | Validation (2025) | Holdout (2026) |")
    lines.append("|---|---|---|")
    lines.append(f"| Horizon / kdz | {m['horizon_bars']} bars / {m['kdz']} | {m['horizon_bars']} bars / {m['kdz']} |")
    lines.append(f"| Rows scored | {val['n_rows']:,} | {ho['n_rows']:,} |")
    lines.append(f"| Primary accuracy | {fmt(val['acc_primary'], pct=True)} | {fmt(ho['acc_primary'], pct=True)} |")
    lines.append(f"| ROC AUC | {fmt(val['auc_primary'], dp=4)} | {fmt(ho['auc_primary'], dp=4)} |")
    lines.append(
        f"| Selective acc @ 20% coverage | "
        f"{fmt(val.get('selective', {}).get('0.2', {}).get('acc'), pct=True)} | "
        f"{fmt(ho.get('selective', {}).get('0.2', {}).get('acc'), pct=True)} |"
    )
    lines.append(
        f"| Policy acc (tau_m = {fmt(val_pol.get('tau_m'), dp=4)}) | "
        f"{fmt(val_pol.get('acc'), pct=True)} | {fmt(ho_pol.get('acc'), pct=True)} |"
    )
    val_ci = val_pol.get("ci95_neff", [float("nan"), float("nan")])
    ho_ci = ho_pol.get("ci95_neff", [float("nan"), float("nan")])
    lines.append(
        f"| 95% Wilson CI (n_eff = n/h) | "
        f"[{fmt(val_ci[0], pct=True)}, {fmt(val_ci[1], pct=True)}] | "
        f"[{fmt(ho_ci[0], pct=True)}, {fmt(ho_ci[1], pct=True)}] |"
    )
    lines.append(
        f"| Always-Up on same candles | "
        f"{fmt(val_pol.get('b1_on_same_candles'), pct=True)} | "
        f"{fmt(ho_pol.get('b1_on_same_candles'), pct=True)} |"
    )
    lines.append(f"| Signals (n) | {val_pol.get('n_signals', '—'):,} | {ho_pol.get('n_signals', '—'):,} |")
    lines.append(f"| Signals per day (248 / 203 days) | {val_sig_day:.1f} | {ho_sig_day:.1f} |")
    lines.append(f"| Policy coverage (of eligible bars) | {fmt(val_pol.get('coverage'), pct=True)} | {fmt(ho_pol.get('coverage'), pct=True)} |")
    lines.append(f"| Permutation p-value | {fmt(val_p, dp=4)} | {fmt(ho_p, dp=4)} |")
    lines.append(f"| Bonferroni-adjusted p ({n_trials} trials) | {fmt(val_p_adj, dp=4)} | — |")
    lines.append(f"| ECE | {fmt(val.get('ece'), dp=4)} | {fmt(ho.get('ece'), dp=4)} |")
    lines.append(
        f"| Brier (calibrated vs constant) | "
        f"{fmt(val.get('brier_conf'), dp=5)} vs {fmt(val.get('brier_const'), dp=5)} | "
        f"{fmt(ho.get('brier_conf'), dp=5)} vs {fmt(ho.get('brier_const'), dp=5)} |"
    )
    band_val = m.get("band_validation", {})
    band_ho = m.get("band_holdout", {})
    lines.append(
        f"| 10–90 band coverage (below / inside / above) | "
        f"{fmt(band_val.get('below_q10'), pct=True, dp=1)} / {fmt(band_val.get('inside'), pct=True, dp=1)} / {fmt(band_val.get('above_q90'), pct=True, dp=1)} | "
        f"{fmt(band_ho.get('below_q10'), pct=True, dp=1)} / {fmt(band_ho.get('inside'), pct=True, dp=1)} / {fmt(band_ho.get('above_q90'), pct=True, dp=1)} |"
    )
    lines.append("")

    # --- P&L table ---
    lines.append("## Net P&L Sensitivity (Basis Points per Signal)\n")
    lines.append(f"*Source: `{METRICS}`*\n")
    lines.append("| Cost per side | Validation Mean (bps) | Validation Excluded | Holdout Mean (bps) | Holdout Excluded |")
    lines.append("|---|---|---|---|---|")
    for c_str in ("0.5", "1.0", "3.0"):
        vp = val_pol.get("pnl_bps", {}).get(c_str, {})
        hp = ho_pol.get("pnl_bps", {}).get(c_str, {})
        lines.append(
            f"| {c_str} bps | {fmt(vp.get('mean_per_signal'), dp=2)} | {val_pol.get('pnl_n_excluded', 0)} | "
            f"{fmt(hp.get('mean_per_signal'), dp=2)} | {ho_pol.get('pnl_n_excluded', 0)} |"
        )
    lines.append("")

    # --- Trial grid ---
    lines.append(f"## Validation Trial Grid (LightGBM Run `{latest_run}`)\n")
    lines.append(f"*Source: `{EXPERIMENTS}` (total logged trials across all runs: {n_trials})*\n")
    if len(lgb_final) > 0:
        lines.append("| Trial | Model | Horizon | kdz | Sel@20% | ECE | AUC | B1 | perm_p |")
        lines.append("|---|---|---|---|---|---|---|---|---|")
        for _, row in lgb_final.iterrows():
            perm_p_col = fmt(row.get("perm_p"), dp=4)
            lines.append(
                f"| {int(row['trial_id'])} | {row['model']} | {int(row['horizon_bars'])} bars | {row['kdz']} | "
                f"{fmt(row.get('selective_acc_20'), pct=True)} | {fmt(row.get('ece'), dp=4)} | "
                f"{fmt(row.get('auc'), dp=4)} | {str(row.get('notes', '')).replace('b1=', '')} | {perm_p_col} |"
            )
    else:
        lines.append("*No LightGBM trials found in experiments.csv.*\n")
    lines.append("")

    # --- Baselines ---
    lines.append("## Baseline Comparison\n")
    lines.append(f"*Source: `{METRICS}`*\n")
    lines.append("| Baseline | Validation | Holdout |")
    lines.append("|---|---|---|")
    lines.append(f"| B1 Always-Up (all scored candles) | {fmt(val.get('b1_always_up'), pct=True)} | {fmt(ho.get('b1_always_up'), pct=True)} |")
    rsi_val = val.get("b2_rsi_rule", {})
    rsi_ho = ho.get("b2_rsi_rule", {})
    lines.append(
        f"| B2 RSI rule (acc, cov) | "
        f"{fmt(rsi_val.get('acc'), pct=True)} ({fmt(rsi_val.get('coverage'), pct=True, dp=1)} cov) | "
        f"{fmt(rsi_ho.get('acc'), pct=True)} ({fmt(rsi_ho.get('coverage'), pct=True, dp=1)} cov) |"
    )
    lines.append(f"| B3 Momentum (`ret_6`) | {fmt(val.get('b3_momentum_ret6'), pct=True)} | {fmt(ho.get('b3_momentum_ret6'), pct=True)} |")
    b4_val = val.get("b4_logistic", {})
    b4_ho = ho.get("b4_logistic", {})
    lines.append(
        f"| B4 Logistic regression (top 20% \\|p−0.5\\|) | "
        f"{fmt(b4_val.get('acc'), pct=True)} (AUC {fmt(b4_val.get('auc'), dp=4)}) | "
        f"{fmt(b4_ho.get('acc'), pct=True)} (AUC {fmt(b4_ho.get('auc'), dp=4)}) |"
    )
    b5_val = val.get("b5_primary_direct", {})
    b5_ho = ho.get("b5_primary_direct", {})
    lines.append(
        f"| B5 LightGBM direct (top 20% \\|p−0.5\\|) | "
        f"{fmt(b5_val.get('acc'), pct=True)} | {fmt(b5_ho.get('acc'), pct=True)} |"
    )
    lines.append("")

    # --- Reliability table ---
    lines.append("## Holdout Calibration Reliability (10 Bins)\n")
    lines.append(f"*Source: `{METRICS}`*\n")
    lines.append("| Bin | Mean Calibrated Conf | Empirical Accuracy | Count |")
    lines.append("|---|---|---|---|")
    for b in ho.get("reliability", []):
        lines.append(f"| {b['b']} | {b['conf']:.4f} | {b['ok']:.4f} | {b['n']:,} |")
    lines.append("")

    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print(f"Written: {OUT}")


if __name__ == "__main__":
    main()

